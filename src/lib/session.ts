// A plain password login for people who don't put the dashboard behind their own
// login (Authentik, Cloudflare Access, Tailscale...). Set DASHBOARD_PASSWORD to turn it on.
// The cookie holds an HMAC of the password, so changing the password signs everyone out.
export const COOKIE = "cc_session";

export async function sessionValue(password: string): Promise<string> {
  const enc = new TextEncoder();
  const key = await crypto.subtle.importKey("raw", enc.encode(password), { name: "HMAC", hash: "SHA-256" }, false, ["sign"]);
  const sig = await crypto.subtle.sign("HMAC", key, enc.encode("command-center-session-v1"));
  return Array.from(new Uint8Array(sig), (b) => b.toString(16).padStart(2, "0")).join("");
}

/** Constant-time string compare that works in any runtime. */
export function same(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let d = 0;
  for (let i = 0; i < a.length; i++) d |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return d === 0;
}
